import type { SocialReplyItem } from '../api'

const terminalReplyStatuses = new Set(['published', 'published_manual', 'rejected'])

export function replyGeneratedBy(reply: SocialReplyItem | null) {
  const generatedBy = reply?.metadata?.generated_by
  const provider = reply?.metadata?.provider
  const model = reply?.metadata?.model
  if (typeof generatedBy === 'string' && generatedBy.trim()) {
    return `${generatedBy}${typeof model === 'string' && model.trim() ? ` · ${model}` : ''}`
  }
  return typeof provider === 'string' && provider.trim() ? `social_reply_agent_v1 · ${provider}` : 'social_reply_agent_v1'
}

export function canRegenerateReply(reply: SocialReplyItem | null) {
  return Boolean(reply?.source_candidate_id && !terminalReplyStatuses.has(reply.status))
}

export function ReplyGeneratedByText({ reply, className = '' }: { reply: SocialReplyItem | null; className?: string }) {
  return <div className={className}>Generated by {replyGeneratedBy(reply)}</div>
}

export function ReplyGeneratedByCard({ reply }: { reply: SocialReplyItem | null }) {
  return (
    <div className="rounded-2xl border border-[color:var(--ops-stroke-soft)] bg-white/[0.03] p-3">
      <div className="text-[10px] uppercase tracking-[0.18em] text-[color:var(--ops-text-caption)]">Generated By</div>
      <div className="mt-2 text-sm text-[color:var(--ops-text-body)]">{replyGeneratedBy(reply)}</div>
    </div>
  )
}

export function RegenerateReplyButton({
  reply,
  busy,
  className = 'rounded-xl border border-cyan-300/35 px-3 py-2 text-sm font-semibold text-cyan-100 disabled:opacity-50',
  onRegenerate,
}: {
  reply: SocialReplyItem | null
  busy: boolean
  className?: string
  onRegenerate: (reply: SocialReplyItem) => void
}) {
  if (!canRegenerateReply(reply)) return null
  return (
    <button type="button" className={className} disabled={busy} onClick={() => onRegenerate(reply!)}>
      {busy ? '生成中...' : '重新生成回帖'}
    </button>
  )
}
